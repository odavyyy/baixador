// Writes THIRD_PARTY_NOTICES.md from the license files of the packages that ship inside the app.
// Usage: node scripts/notices.mjs   (run after `npm ci`)
import fs from 'node:fs';
import path from 'node:path';

const SHIPPED = [
  ['electron', 'Application runtime (includes Chromium and Node.js; their notices ship as LICENSES.chromium.html next to the app)'],
  ['react', 'UI library'],
  ['react-dom', 'UI library'],
  ['scheduler', 'Dependency of react-dom'],
  ['lucide-react', 'Icons'],
  ['@fontsource-variable/inter', 'Inter typeface (bundled font files)'],
];

const findLicense = (dir) => fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.md|\.txt)?$/i.test(f));

let out = `# Third-party notices

Baixador is distributed under the MIT License (see LICENSE). The packaged app also contains the
following third-party software. This file is generated by \`scripts/notices.mjs\`.

Not included: **yt-dlp** and the **FFmpeg** command-line tools (ffmpeg.exe / ffprobe.exe) are *not*
bundled or redistributed with Baixador. The app runs the copies that you install yourself, under their
own licenses (yt-dlp: Unlicense; FFmpeg: LGPL/GPL depending on the build).

Note: Electron itself ships \`ffmpeg.dll\`, Chromium's LGPL build of the FFmpeg libraries that Chromium
uses for media playback. Baixador does not call it; it is part of Electron and is covered by
LICENSES.chromium.html.

| Package | Version | License | Used for |
|---|---|---|---|
`;
const texts = [];
for (const [name, use] of SHIPPED) {
  const dir = path.join('node_modules', name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  out += `| ${name} | ${pkg.version} | ${pkg.license} | ${use} |\n`;
  const lic = findLicense(dir);
  texts.push(`## ${name} ${pkg.version}\n\n\`\`\`\n${lic ? fs.readFileSync(path.join(dir, lic), 'utf8').trim() : `License: ${pkg.license} (no license file in package)`}\n\`\`\`\n`);
}
out += '\n' + texts.join('\n');
fs.writeFileSync('THIRD_PARTY_NOTICES.md', out);
console.log('THIRD_PARTY_NOTICES.md written');
